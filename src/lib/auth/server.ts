/**
 * Better Auth instance.
 *
 * The prototype's "auth" was `localStorage.setItem("bt_user", …)` — any
 * visitor could mint themselves an account, a role, or someone else's
 * identity from the browser console. This is the replacement: email+password
 * plus Google and Apple, sessions in Postgres, and every check on the server.
 *
 * SHAPE NOTES — read before changing `user`/`account` below.
 *
 * The tables in `src/db/schema/auth.ts` were designed for this product, not
 * generated from Better Auth's defaults, so three of their columns do not
 * line up with the framework's model. All three are reconciled here, in
 * configuration, rather than by migrating a schema another part of the app
 * already reads:
 *
 *  1. `users.email_verified_at` is a nullable timestamp; Better Auth's
 *     `emailVerified` is a boolean. The field is redeclared with a
 *     `transform` pair so the boolean is stored as a verification *instant*
 *     (which is the more useful record) and read back as a boolean.
 *  2. `accounts.password_hash` carries the credential hash; Better Auth calls
 *     it `password`. A plain name remap.
 *  3. `accounts` has no `id_token` or `refresh_token_expires_at` column. Both
 *     are declared with an input transform that returns `undefined`, which
 *     drops them before they reach Drizzle — the adapter throws on any key
 *     absent from the table object. Neither is needed: sessions here are
 *     server-side, so the provider's id token has no job after the callback,
 *     and neither Google nor Apple returns a refresh-token expiry.
 *
 * Ids are NOT generated by Better Auth. Every primary key in this schema is
 * `uuid ... default gen_random_uuid()`, and Better Auth's default generator
 * emits a 32-character base36 string that Postgres rejects for a `uuid`
 * column. `advanced.database.generateId: false` hands id generation back to
 * the database.
 *
 * KNOWN GAP: `users.two_factor_enabled` exists and `roles.ts` states that
 * staff and admin must carry TOTP, but Better Auth's two-factor plugin needs
 * a `twoFactor` table this schema does not have. 2FA is therefore *not*
 * enforced here — wiring it needs a migration, which this file does not own.
 * `requireCapability()` deliberately does not gate on the flag, because doing
 * so would lock every elevated account out with no route to enrol.
 */

