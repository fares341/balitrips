import { drizzleAdapter } from 'better-auth/adapters/drizzle'
import { nextCookies } from 'better-auth/next-js'
import { APIError, createAuthMiddleware, isAPIError } from 'better-auth/api'
import { and, eq, isNull } from 'drizzle-orm'

import { db } from '@/db'
import { accounts, sessions, users, verifications } from '@/db/schema'
import { defaultLocale, isLocale } from '@/i18n/config'

import { logActivity } from '@/lib/security/activity'
import { findActiveBan } from '@/lib/security/bans'
import {
  DeviceApprovalPendingError,
  DeviceBannedError,
  DeviceLimitError,
  registerSignInDevice,
} from '@/lib/security/devices'
import { DEVICE_COOKIE, deviceIdentity } from '@/lib/security/fingerprint'
import { clientIp, requestCity, requestCountry } from '@/lib/security/ip'

import { looksLikeEmail, normalizePhone } from './phone'

import { sendPasswordResetEmail, sendVerificationEmail, toMailLocale } from './email'

/* --------------------------------------------------------------------------
   Environment
   -------------------------------------------------------------------------- */

/** Public origin, no trailing slash. OAuth callbacks are built from this. */
const BASE_URL = (
  process.env.BETTER_AUTH_URL ??
  process.env.NEXT_PUBLIC_SITE_URL ??
  'http://localhost:3000'
).replace(/\/+$/, '')

const SECRET = process.env.BETTER_AUTH_SECRET

if (process.env.NODE_ENV === 'production' && (SECRET === undefined || SECRET === '')) {
  // Without a secret, session cookies and the cookie cache are signed with a
  // value an attacker can guess. Fail at boot rather than serve forgeable
  // sessions.
  throw new Error('BETTER_AUTH_SECRET is not set')
}

/** A provider is wired only when BOTH halves of its credential pair exist. */
function credentials(idVar: string, secretVar: string): { id: string; secret: string } | null {
  const id = process.env[idVar]
  const secret = process.env[secretVar]
  if (id === undefined || id === '' || secret === undefined || secret === '') return null
  return { id, secret }
}

const googleCredentials = credentials('GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET')
const appleCredentials = credentials('APPLE_CLIENT_ID', 'APPLE_CLIENT_SECRET')

export const SOCIAL_PROVIDER_IDS = ['google', 'apple'] as const
export type SocialProviderId = (typeof SOCIAL_PROVIDER_IDS)[number]

/**
 * Which social buttons the sign-in sheet should render.
 *
 * Read this from a Server Component and pass it to `<AuthModal>`: a button
 * for a provider with no client id would send the visitor to a 400.
 *
 * ⚠︎ Call it only from a *dynamically* rendered page. Env is re-read here
 * rather than captured at module load, but that is not enough on its own: a
 * prerendered page bakes whatever this returned at `next build`, and the
 * build container has no OAuth credentials — every visitor would then get a
 * sheet with no social buttons until the next deploy.
 */
export function enabledSocialProviders(): readonly SocialProviderId[] {
  const enabled: SocialProviderId[] = []
  if (credentials('GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET') !== null) enabled.push('google')
  if (credentials('APPLE_CLIENT_ID', 'APPLE_CLIENT_SECRET') !== null) enabled.push('apple')
  return enabled
}

/* --------------------------------------------------------------------------
   Durations
   -------------------------------------------------------------------------- */

const MINUTE = 60
const HOUR = 60 * MINUTE
const DAY = 24 * HOUR

/**
 * Cookie cache window.
 *
 * Without it every `getSession()` is a database round trip, and a Server
 * Component tree calls it on every render — the header, the account menu and
 * any gated section each pay for the same lookup. Five minutes is the ceiling
 * on how long a revoked session can survive: `revokeSessionsOnPasswordReset`
 * below deletes the rows immediately, but a cached cookie stays valid until
 * it expires.
 */
const COOKIE_CACHE_MAX_AGE = 5 * MINUTE

/* --------------------------------------------------------------------------
   Instance
   -------------------------------------------------------------------------- */

export const auth = betterAuth({
  appName: 'Bali Trips',
  baseURL: BASE_URL,
  basePath: '/api/auth',
  ...(SECRET === undefined || SECRET === '' ? {} : { secret: SECRET }),
  trustedOrigins: [BASE_URL],

  database: drizzleAdapter(db, {
    provider: 'pg',
    // Keys are Better Auth's model names; values are this project's tables.
    schema: {
      user: users,
      session: sessions,
      account: accounts,
      verification: verifications,
    },
  }),

  /* ---- Email + password ------------------------------------------------ */

  emailAndPassword: {
    enabled: true,
    // Matches the zod rule the sign-up form enforces client-side. Both exist:
    // the client rule is UX, this one is the boundary.
    minPasswordLength: 8,
    maxPasswordLength: 128,
    autoSignIn: true,
    /**
     * Verification is not required to sign in.
     *
     * There is no verify-email screen in this build, and requiring
     * verification without one would strand every new account. The column is
     * still written when a social provider asserts a verified address.
     */
    requireEmailVerification: false,
    resetPasswordTokenExpiresIn: HOUR,
    /**
     * Resetting a password kills every other session.
     *
     * The common reason to reset is "someone else may have my password"; a
     * reset that leaves the attacker's session alive answers the wrong
     * question.
     */
    revokeSessionsOnPasswordReset: true,

    sendResetPassword: async ({ user, url }) => {
      await sendPasswordResetEmail({
        to: user.email,
        name: user.name ?? null,
        url,
        locale: toMailLocale((user as { locale?: unknown }).locale),
      })
    },
  },

  /* ---- Email verification --------------------------------------------- */

  /**
   * رابط تأكيد البريد عند التسجيل (ومن صفحة الحساب لإعادة الإرسال). لا يمنع
   * الدخول؛ بعد التأكيد يعود المستخدم لصفحة حسابه بلغته.
   */
  emailVerification: {
    sendOnSignUp: true,
    autoSignInAfterVerification: true,
    expiresIn: DAY,
    sendVerificationEmail: async ({ user, token }) => {
      const locale = toMailLocale((user as { locale?: unknown }).locale)
      const callbackURL = `/${locale}/account?verified=1`
      const url = `${BASE_URL}/api/auth/verify-email?token=${encodeURIComponent(token)}&callbackURL=${encodeURIComponent(callbackURL)}`
      await sendVerificationEmail({
        to: user.email,
        name: user.name ?? null,
        url,
        siteUrl: `${BASE_URL}/${locale}`,
        locale,
      })
    },
  },

  /* ---- Social ---------------------------------------------------------- */

  socialProviders: {
    ...(googleCredentials === null
      ? {}
      : {
          google: {
            clientId: googleCredentials.id,
            clientSecret: googleCredentials.secret,
          },
        }),
    ...(appleCredentials === null
      ? {}
      : {
          apple: {
            clientId: appleCredentials.id,
            // NOTE: Apple's "secret" is a JWT that expires within six months.
            // When sign-in with Apple starts failing, this is the first thing
            // to check.
            clientSecret: appleCredentials.secret,
            ...(process.env.APPLE_BUNDLE_ID === undefined || process.env.APPLE_BUNDLE_ID === ''
              ? {}
              : { appBundleIdentifier: process.env.APPLE_BUNDLE_ID }),
          },
        }),
  },

  /* ---- Account linking ------------------------------------------------- */

  account: {
    fields: {
      // `accounts.password_hash`.
      password: 'passwordHash',
    },
    additionalFields: {
      // See SHAPE NOTES 3. Dropped before they reach Drizzle.
      idToken: {
        type: 'string',
        required: false,
        input: false,
        returned: false,
        transform: { input: () => undefined, output: () => undefined },
      },
      refreshTokenExpiresAt: {
        type: 'date',
        required: false,
        input: false,
        returned: false,
        transform: { input: () => undefined, output: () => undefined },
      },
    },
    accountLinking: {
      enabled: true,
      /**
       * Only providers that verify the address may auto-link.
       *
       * Linking on an unverified email lets anyone who can create an account
       * at a sloppy provider claim an existing Bali Trips account by
       * asserting its address.
       */
      trustedProviders: ['google', 'apple'],
    },
  },

  /* ---- User ------------------------------------------------------------ */

  user: {
    additionalFields: {
      /**
       * See SHAPE NOTE 1. `fieldName` names the key on the Drizzle table
       * object, and the transform pair converts boolean <-> timestamp at the
       * adapter boundary so nothing above this line has to know.
       */
      emailVerified: {
        type: 'boolean',
        required: true,
        input: false,
        defaultValue: false,
        fieldName: 'emailVerifiedAt',
        transform: {
          input: (value) => (value === true ? new Date() : null),
          output: (value) => value instanceof Date,
        },
      },
      /**
       * Authorization role. `input: false` is the important part — without
       * it, `role: "admin"` in a sign-up body would be persisted verbatim.
       */
      role: {
        type: 'string',
        required: true,
        input: false,
        returned: true,
        defaultValue: 'customer',
      },
      /**
       * Soft delete. Read by `getSession()` in ./session, which treats a
       * deleted user as signed out — Better Auth has no concept of the
       * column and would otherwise happily keep issuing sessions.
       */
      deletedAt: {
        type: 'date',
        required: false,
        input: false,
        returned: true,
      },
      /** Language for transactional mail. Sanitized in the hook below. */
      locale: {
        type: 'string',
        required: false,
        returned: true,
        defaultValue: defaultLocale,
      },
      phone: { type: 'string', required: false, returned: true },
      /** يُحسب في الخطاف أدناه من `phone`؛ لا يقبله أحد من جسم الطلب. */
      phoneNormalized: { type: 'string', required: false, input: false, returned: false },
      country: { type: 'string', required: false, returned: true },
      /**
       * الحظر. `input: false` حتى لا يرسله أحد في جسم التسجيل؛ `returned`
       * حتى يقرأه `getSession()` ويعامل المحظور كغير مسجّل.
       */
      status: {
        type: 'string',
        required: false,
        input: false,
        returned: true,
        defaultValue: 'active',
      },
      bannedUntil: { type: 'date', required: false, input: false, returned: true },
    },
  },

  /* ---- Sessions -------------------------------------------------------- */

  session: {
    additionalFields: {
      /** يُملأ في `databaseHooks.session.create.before` أدناه. */
      deviceId: { type: 'string', required: false, input: false, returned: false },
    },
    expiresIn: 7 * DAY,
    updateAge: DAY,
    // Re-authentication window for destructive operations (account delete).
    freshAge: DAY,
    cookieCache: {
      enabled: true,
      maxAge: COOKIE_CACHE_MAX_AGE,
    },
  },

  /* ---- Input sanitation ------------------------------------------------ */

  databaseHooks: {
    /**
     * الأمان عند تسجيل الدخول — انظر src/lib/security.
     *
     * كل جلسة جديدة (بريد/كلمة مرور، Google، Apple، أو الدخول التلقائي بعد
     * التسجيل) تمر من هنا: فحص الحظر (مستخدم/جهاز/IP)، ثم تسجيل الجهاز
     * وتطبيق حد الأجهزة، ثم ربط الجلسة بالجهاز.
     *
     * `ctx === null` يعني استدعاءً داخلياً بلا طلب HTTP؛ لا يوجد ما نبصمه.
     */
    session: {
      create: {
        before: async (session, ctx) => {
          if (ctx === null) return

          const userId = String(session.userId)
          const ip = (ctx.headers ? clientIp(ctx.headers) : null) ?? asIp(session.ipAddress)
          const userAgent =
            ctx.headers?.get('user-agent') ??
            (typeof session.userAgent === 'string' ? session.userAgent : null)
          const identity = deviceIdentity(ctx.getCookie(DEVICE_COOKIE), userAgent)

          const ban = await findActiveBan({ userId, fingerprintHash: identity.fingerprintHash, ip })
          if (ban !== null) {
            await logActivity({
              action: 'login_blocked',
              userId,
              ip,
              details: { why: `banned_${ban}` },
            })
            throw APIError.from('FORBIDDEN', {
              message: 'This account cannot sign in.',
              code: 'ACCOUNT_BANNED',
            })
          }

          try {
            const deviceId = await registerSignInDevice({ userId, identity, userAgent, ip })
            // تسجيل الجهاز قد يطلق حظراً تلقائياً (تبديل الأجهزة المتكرر).
            // نعيد الفحص كي لا تُنشأ جلسة لحساب حُظر للتو في نفس الطلب.
            if ((await findActiveBan({ userId })) !== null) {
              throw APIError.from('FORBIDDEN', {
                message: 'This account cannot sign in.',
                code: 'ACCOUNT_BANNED',
              })
            }
            return { data: { ...session, deviceId } }
          } catch (error) {
            if (error instanceof DeviceLimitError) {
              await logActivity({
                action: 'device_limit_blocked',
                userId,
                ip,
                details: {
                  limit: error.limit,
                  active: error.active,
                  browser: identity.browser,
                  os: identity.os,
                },
              })
              throw APIError.from('FORBIDDEN', {
                message: 'Device limit reached.',
                code: 'DEVICE_LIMIT_REACHED',
              })
            }
            if (error instanceof DeviceApprovalPendingError) {
              // سُجّل في registerSignInDevice؛ هنا نعيد رسالة "بانتظار موافقة الإدارة".
              throw APIError.from('FORBIDDEN', {
                message: 'This device is waiting for approval.',
                code: 'DEVICE_PENDING_APPROVAL',
              })
            }
            if (error instanceof DeviceBannedError) {
              await logActivity({
                action: 'login_blocked',
                userId,
                ip,
                details: { why: 'device_banned' },
              })
              throw APIError.from('FORBIDDEN', {
                message: 'This account cannot sign in.',
                code: 'ACCOUNT_BANNED',
              })
            }
            throw error
          }
        },
        after: async (session, ctx) => {
          await logActivity({
            action: 'login',
            userId: String(session.userId),
            ip: (ctx?.headers ? clientIp(ctx.headers) : null) ?? asIp(session.ipAddress),
            deviceId: typeof session.deviceId === 'string' ? session.deviceId : null,
            // الوثيقة 3.2: "الموقع التقريبي إن أمكن" — الدولة من رأس الـ CDN إن وُجد.
            details: {
              ...(ctx?.path ? { via: ctx.path } : {}),
              country: ctx?.headers ? requestCountry(ctx.headers) : null,
              city: ctx?.headers ? requestCity(ctx.headers) : null,
            },
          })
        },
      },
      delete: {
        before: async (session, ctx) => {
          // تسجيل الخروج فقط؛ حذف الجلسات المنتهية في الخلفية ليس "خروجاً".
          if (ctx?.path !== '/sign-out') return
          await logActivity({
            action: 'logout',
            userId: String(session.userId),
            ip: ctx.headers ? clientIp(ctx.headers) : null,
            deviceId: typeof session.deviceId === 'string' ? session.deviceId : null,
          })
        },
      },
    },
    user: {
      create: {
        /**
         * `locale`, `phone` and `country` arrive from the sign-up body, so
         * they are attacker-controlled strings hitting `varchar(5)`,
         * `varchar(32)` and `varchar(2)` columns. Postgres would reject an
         * over-long value with a 500 that leaks the column definition; a
         * bogus locale would silently break the reset email. Normalize here,
         * inside the transaction that creates the row.
         */
        before: async (user, ctx) => {
          const raw = user as Record<string, unknown>
          const rawLocale = raw.locale
          const rawPhone = raw.phone
          const rawCountry = raw.country

          // الوثيقة 3.1: الجوال من بيانات التسجيل، وهو مفتاح دخول — فريد ودولي.
          const phoneNormalized = typeof rawPhone === 'string' ? normalizePhone(rawPhone) : null
          if (ctx?.path === '/sign-up/email' && phoneNormalized === null) {
            throw APIError.from('BAD_REQUEST', {
              message: 'A mobile number in international format is required.',
              code: 'PHONE_REQUIRED',
            })
          }
          if (phoneNormalized !== null && (await phoneTaken(phoneNormalized))) {
            throw APIError.from('BAD_REQUEST', {
              message: 'This mobile number is already registered.',
              code: 'PHONE_TAKEN',
            })
          }

          return {
            data: {
              ...user,
              phoneNormalized,
              locale:
                typeof rawLocale === 'string' && isLocale(rawLocale) ? rawLocale : defaultLocale,
              phone:
                typeof rawPhone === 'string' && rawPhone.trim() !== ''
                  ? rawPhone.trim().slice(0, 32)
                  : null,
              country:
                typeof rawCountry === 'string' && /^[A-Za-z]{2}$/.test(rawCountry)
                  ? rawCountry.toUpperCase()
                  : null,
            },
          }
        },
        /**
         * رسالة الترحيب عند إنشاء حساب (الوثيقة: إشعار عند إنشاء حساب جديد).
         * القالب والمهمة موجودان منذ البداية لكن لا شيء كان يضعها في الطابور.
         * فشل الطابور لا يُفشل التسجيل.
         */
        after: async (user) => {
          // التسجيل بالبريد: رسالة الترحيب هي رسالة التأكيد (`emailVerification`)،
          // فلا نرسل رسالتين. حساب Google/Apple مؤكَّد أصلاً: ترحيب عادي.
          const record = user as { emailVerified?: unknown; emailVerifiedAt?: unknown }
          const verified = record.emailVerified === true || record.emailVerifiedAt instanceof Date
          if (!verified) return
          try {
            const { enqueueEmail } = await import('@/worker/queues')
            await enqueueEmail({ kind: 'welcome', userId: String(user.id) })
          } catch (error) {
            console.error('[auth] could not queue the welcome email', error)
          }
        },
      },
      /**
       * نفس التنقية عند التعديل: نقطة `update-user` في Better Auth تقبل هذه
       * الحقول مباشرة، فقيمة طويلة كانت تنتهي بخطأ 500 من Postgres.
       */
      update: {
        before: async (user, ctx) => {
          const raw = user as Record<string, unknown>
          const data: Record<string, unknown> = { ...user }
          if ('locale' in raw) {
            data.locale =
              typeof raw.locale === 'string' && isLocale(raw.locale) ? raw.locale : defaultLocale
          }
          if ('phone' in raw) {
            data.phone =
              typeof raw.phone === 'string' && raw.phone.trim() !== ''
                ? raw.phone.trim().slice(0, 32)
                : null
            const normalized = typeof raw.phone === 'string' ? normalizePhone(raw.phone) : null
            // بيانات التعديل لا تحمل المعرّف؛ صاحب الجلسة هو من يعدّل حسابه.
            const sessionUser = (
              ctx?.context as { session?: { user?: { id?: unknown } } } | undefined
            )?.session?.user
            const self = typeof sessionUser?.id === 'string' ? sessionUser.id : undefined
            if (normalized !== null && (await phoneTaken(normalized, self))) {
              throw APIError.from('BAD_REQUEST', {
                message: 'This mobile number is already registered.',
                code: 'PHONE_TAKEN',
              })
            }
            data.phoneNormalized = normalized
          }
          if ('country' in raw) {
            data.country =
              typeof raw.country === 'string' && /^[A-Za-z]{2}$/.test(raw.country)
                ? raw.country.toUpperCase()
                : null
          }
          return { data: data as typeof user }
        },
      },
    },
  },

  /* ---- Activity hooks -------------------------------------------------- */

  hooks: {
    /**
     * الدخول برقم الجوال (الوثيقة 3.2): خانة الدخول تقبل بريداً أو جوالاً.
     * جوال ← نبحث عن الحساب بالرقم الموحّد ونمرّر بريده لنقطة الدخول العادية،
     * فتبقى كل الحماية (حد المحاولات، الأجهزة، الحظر، السجل) كما هي.
     * رقم بلا حساب ← عنوان لا يوجد، فتعود نفس رسالة "بيانات غير صحيحة" (لا كشف
     * لوجود حساب).
     */
    before: createAuthMiddleware(async (ctx) => {
      if (ctx.path !== '/sign-in/email') return
      const body = (ctx.body ?? {}) as Record<string, unknown>
      const identifier = typeof body.email === 'string' ? body.email.trim() : ''
      if (identifier === '' || looksLikeEmail(identifier)) return
      const normalized = normalizePhone(identifier)
      const [owner] =
        normalized === null
          ? []
          : await db
              .select({ email: users.email })
              .from(users)
              .where(and(eq(users.phoneNormalized, normalized), isNull(users.deletedAt)))
              .limit(1)
      // نعيد الجزء المتغيّر فقط: Better Auth يدمج `context` المُعاد مع السياق الحالي.
      return { context: { body: { ...body, email: owner?.email ?? PHONE_NOT_FOUND_EMAIL } } }
    }),

    /**
     * محاولات الدخول الفاشلة. تُسجَّل مع البريد المُدخل (بأحرف صغيرة)، ومع
     * `user_id` إن كان الحساب موجوداً — وهو ما سيعدّه الحظر التلقائي.
     * لا شيء من هذا يصل للعميل؛ رسالة الخطأ تبقى موحّدة (انظر client.ts).
     */
    after: createAuthMiddleware(async (ctx) => {
      // تغيير كلمة المرور من الحساب (الوثيقة 15.1).
      if (ctx.path === '/change-password') {
        const userId = ctx.context.session?.user.id ?? ctx.context.newSession?.user.id
        if (userId !== undefined && !isAPIError(ctx.context.returned)) {
          await logActivity({
            action: 'change_password',
            userId: String(userId),
            ip: ctx.headers ? clientIp(ctx.headers) : null,
            details: { via: 'account' },
          })
        }
        return
      }
      if (ctx.path === '/reset-password' && !isAPIError(ctx.context.returned)) {
        await logActivity({
          action: 'change_password',
          ip: ctx.headers ? clientIp(ctx.headers) : null,
          details: { via: 'reset_link' },
        })
        return
      }
      if (ctx.path !== '/sign-in/email') return
      const returned = ctx.context.returned
      if (!isAPIError(returned)) return
      if (
        returned.body?.code === 'DEVICE_LIMIT_REACHED' ||
        returned.body?.code === 'DEVICE_PENDING_APPROVAL' ||
        returned.body?.code === 'ACCOUNT_BANNED'
      ) {
        return // سُجّلت أعلاه بسببها الحقيقي
      }

      const body = (ctx.body ?? {}) as Record<string, unknown>
      const email =
        typeof body.email === 'string' ? body.email.trim().toLowerCase().slice(0, 256) : null
      const [owner] =
        email === null
          ? []
          : await db.select({ id: users.id }).from(users).where(eq(users.email, email)).limit(1)

      await logActivity({
        action: 'login_failed',
        userId: owner?.id ?? null,
        ip: ctx.headers ? clientIp(ctx.headers) : null,
        details: { email, code: returned.body?.code ?? null, status: returned.status },
      })
    }),
  },

  /* ---- Rate limiting --------------------------------------------------- */

  /**
   * The handoff had none: its sign-in form was a `preventDefault` that always
   * succeeded, so there was nothing to throttle. With real credentials the
   * endpoints below are the two things worth attacking — password guessing
   * and reset-mail flooding — and both are cheap for the attacker and
   * expensive for us.
   *
   * Storage is in-process. `storage: "database"` needs a `rateLimit` table
   * this schema does not have, and there is no Redis in the stack; the
   * deployment is a single Next container, so one process is one bucket. If
   * the app is ever scaled horizontally this MUST move to shared storage —
   * N replicas would otherwise multiply every limit below by N.
   *
   * Paths are relative to `basePath`.
   */
  rateLimit: {
    // Better Auth only enables this in production by default. Development and
    // CI should exercise the same code path.
    enabled: true,
    window: MINUTE,
    max: 60,
    storage: 'memory',
    customRules: {
      // Credential stuffing.
      '/sign-in/email': { window: 5 * MINUTE, max: 5 },
      '/sign-up/email': { window: HOUR, max: 5 },
      '/change-password': { window: 5 * MINUTE, max: 5 },
      '/change-email': { window: HOUR, max: 5 },
      // Mail flooding — an unthrottled reset form is a spam cannon aimed at
      // whichever address the attacker types, and it burns sending reputation.
      '/request-password-reset': { window: HOUR, max: 5 },
      '/forget-password': { window: HOUR, max: 5 },
      '/reset-password': { window: HOUR, max: 10 },
      '/send-verification-email': { window: HOUR, max: 5 },
      // OAuth round trips are user-initiated but cheap to replay.
      '/sign-in/social': { window: 5 * MINUTE, max: 10 },
      '/callback/*': { window: 5 * MINUTE, max: 20 },
      // Read-only and hit on navigation; the cookie cache already absorbs
      // most of these, but the default 60/min is too tight for a fast browse.
      '/get-session': { window: MINUTE, max: 120 },
    },
  },

  /* ---- Advanced -------------------------------------------------------- */

  advanced: {
    cookiePrefix: 'bt',
    database: {
      // See the header: uuid primary keys with a database-side default.
      generateId: false,
    },
    ipAddress: {
      /**
       * The rate-limit key is derived from this. Caddy terminates TLS and
       * sets `x-forwarded-for`; nothing else may be trusted, because a header
       * a client can set is a header a client can rotate to get a fresh
       * bucket per request.
       */
      // نفس مصدر src/lib/security/ip.ts: خلف Cloudflare يكون `cf-connecting-ip`،
      // وإلا تحسب كل الزيارات عنوان حافة Cloudflare نفسه ويتشارك الكل حداً واحداً.
      ipAddressHeaders: trustedIpHeaders(),
    },
  },

  /**
   * Must stay last. `nextCookies` runs an after-hook that copies Set-Cookie
   * onto the Next response, which is what makes sign-in work from a Server
   * Action rather than only from a fetch.
   */
  plugins: [nextCookies()],
})

