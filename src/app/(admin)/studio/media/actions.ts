/**
 * Media library mutations.
 *
 * Upload is the one that matters: it is the reason `hero_image_id` was null
 * on every record in the database and the reason placeholder art had to be
 * generated by a script. The pipeline in `_lib/image/` already existed and
 * was already tested — nothing here re-implements sniffing, capping,
 * stripping or encoding, it only wires the pipeline to a form and a row.
 *
 * ORDER MATTERS on upload. The id is minted BEFORE the bytes are processed,
 * because every object key derives from it (`media/<id>/1280.avif`), and the
 * row is written LAST, inside a transaction, so a failed encode cannot leave
 * a database row pointing at objects that were never stored. The reverse —
 * storing objects for a row that then fails to insert — leaves orphaned bytes
 * in a bucket, which is wasteful but not incorrect, and is the direction to
 * fail if one has to be chosen.
 */

const LIST = adminHref('/media')

type Outcome = { ok: string } | { err: string }

/**
 * Ingest one image.
 *
 * `media.upload` rather than `content.write`: uploading is a distinct
 * capability because it consumes storage and is the one admin action that
 * accepts arbitrary bytes from outside.
 */
export async function uploadMedia(form: FormData): Promise<void> {
  const session = await requireCapability('media.upload')
  const { t } = await getAdminI18n()
  let outcome: Outcome

  try {
    const file = form.get('file')
    if (!(file instanceof File) || file.size === 0) {
      throw new Error(t('media.err_choose_image'))
    }

    // Checked before the body is read into memory. `file.size` is the
    // multipart part's declared length, so this is a cheap first gate; the
    // pipeline checks the actual byte length again after buffering.
    if (file.size > MAX_UPLOAD_BYTES) {
      throw new Error(
        t('media.err_too_large', {
          size: formatBytes(file.size),
          max: formatBytes(MAX_UPLOAD_BYTES),
        }),
      )
    }

    const alt = flocalized(form, 'alt')
    const credit = fstr(form, 'credit')

    // Minted here: the object keys are a pure function of it, so it has to
    // exist before anything is written to storage.
    const mediaId = randomUUID()

    const result = await ingestImage({
      mediaId,
      bytes: new Uint8Array(await file.arrayBuffer()),
      declaredMime: file.type === '' ? null : file.type,
      declaredName: file.name === '' ? null : file.name,
    })

    const inserted = await db.transaction(async (tx) => {
      const [row] = await tx
        .insert(media)
        .values({
          id: mediaId,
          objectKey: result.objectKey,
          mimeType: result.mimeType,
          width: result.width,
          height: result.height,
          bytes: result.bytes,
          alt,
          credit,
        })
        .returning()

      if (!row) throw new Error(t('media.err_row_write'))

      await writeAudit(
        {
          actor: session,
          action: 'media.upload',
          entityType: 'media',
          entityId: row.id,
          before: null,
          after: {
            objectKey: row.objectKey,
            mimeType: row.mimeType,
            width: row.width,
            height: row.height,
            bytes: row.bytes,
            credit: row.credit,
            derivatives: result.derivatives.length,
            optimised: result.optimised,
            driver: result.driver,
            originalName: file.name,
          },
        },
        tx,
      )

      return row
    })

    outcome = {
      ok: result.optimised
        ? t('media.ok_uploaded', {
            width: inserted.width,
            height: inserted.height,
            size: formatBytes(inserted.bytes),
            count: result.derivatives.length,
          })
        : t('media.ok_uploaded_unoptimised', {
            width: inserted.width,
            height: inserted.height,
            size: formatBytes(inserted.bytes),
          }),
    }
  } catch (error) {
    if (isRedirectError(error)) throw error
    // ImageRejected messages say exactly what was wrong with the file; they
    // are technical English, so the sentence around them is translated.
    outcome = {
      err:
        error instanceof ImageRejected
          ? t('media.err_rejected', { detail: error.message })
          : errorMessage(error),
    }
  }

  redirect(withOutcome(LIST, outcome))
}

/**
 * Alt text and credit.
 *
 * Alt is per-locale because it is content, not metadata — an Arabic page with
 * an English alt attribute is as broken for a screen reader as no alt at all.
 * Blank locales are legitimate: `pick()` falls back to English.
 */
export async function updateMedia(id: string, form: FormData): Promise<void> {
  const session = await requireCapability('media.upload')
  const { t } = await getAdminI18n()
  let outcome: Outcome

  try {
    const values = {
      alt: flocalized(form, 'alt'),
      credit: fstr(form, 'credit'),
    }

    await db.transaction(async (tx) => {
      const [before] = await tx.select().from(media).where(eq(media.id, id)).limit(1)
      if (!before) throw new Error(t('media.err_gone'))

      const [after] = await tx.update(media).set(values).where(eq(media.id, id)).returning()

      await writeAudit(
        {
          actor: session,
          action: 'media.update',
          entityType: 'media',
          entityId: id,
          before: { alt: before.alt, credit: before.credit },
          after: { alt: after?.alt ?? null, credit: after?.credit ?? null },
        },
        tx,
      )
    })

    outcome = { ok: t('media.ok_saved') }
  } catch (error) {
    if (isRedirectError(error)) throw error
    outcome = { err: errorMessage(error) }
  }

  redirect(withOutcome(returnTo(form), outcome))
}

/**
 * Soft delete.
 *
 * Refused while any PUBLISHED record points at the image. The foreign key
 * would happily survive — `hero_image_id` still resolves — but the public
 * query treats a soft-deleted row as no image, so the live page would lose
 * its hero silently. The message names the offending records so the operator
 * can go and repoint them.
 *
 * The media row is locked FOR UPDATE and the reference check runs inside the
 * same transaction, so two operators archiving the same image serialise and
 * the second one sees the first one's result.
 *
 * HONEST LIMIT: that does NOT close the window against a concurrent *publish*.
 * Under READ COMMITTED this transaction cannot see a publish that commits
 * after its reference read, and closing it properly would mean the publish
 * path taking a lock on `media` — which lives in another slice. The residual
 * race archives an image that became live moments earlier; it is recoverable
 * with one click on Restore, and the audit row says exactly when it happened.
 */
export async function deleteMedia(id: string, form: FormData): Promise<void> {
  const session = await requireCapability('media.upload')
  const { t } = await getAdminI18n()
  let outcome: Outcome

  try {
    await db.transaction(async (tx) => {
      const [before] = await tx
        .select()
        .from(media)
        .where(and(eq(media.id, id), isNull(media.deletedAt)))
        .for('update')
        .limit(1)

      if (!before) throw new Error(t('media.err_already_archived'))

      const blocking = publishedReferences(await referencesTo(id, tx))
      if (blocking.length > 0) {
        const named = blocking
          .slice(0, 4)
          .map((reference) => `${reference.entity} “${reference.label}”`)
          .join(', ')
        const more = blocking.length > 4 ? t('media.and_more', { count: blocking.length - 4 }) : ''
        throw new Error(t('media.err_still_used', { count: blocking.length, named, more }))
      }

      await tx.update(media).set({ deletedAt: new Date() }).where(eq(media.id, id))

      await writeAudit(
        {
          actor: session,
          action: 'media.delete',
          entityType: 'media',
          entityId: id,
          before: { objectKey: before.objectKey, deletedAt: null },
          after: { objectKey: before.objectKey, deletedAt: new Date().toISOString() },
        },
        tx,
      )
    })

    outcome = {
      ok: t('media.ok_archived'),
    }
  } catch (error) {
    if (isRedirectError(error)) throw error
    outcome = { err: errorMessage(error) }
  }

  redirect(withOutcome(returnTo(form), outcome))
}

/** Undo an archive. The objects were never removed, so this is a flag flip. */
export async function restoreMedia(id: string, form: FormData): Promise<void> {
  const session = await requireCapability('media.upload')
  const { t } = await getAdminI18n()
  let outcome: Outcome

  try {
    await db.transaction(async (tx) => {
      const [before] = await tx
        .select()
        .from(media)
        .where(and(eq(media.id, id), isNotNull(media.deletedAt)))
        .limit(1)

      if (!before) throw new Error(t('media.err_not_archived'))

      await tx.update(media).set({ deletedAt: null }).where(eq(media.id, id))

      await writeAudit(
        {
          actor: session,
          action: 'media.restore',
          entityType: 'media',
          entityId: id,
          before: { deletedAt: before.deletedAt?.toISOString() ?? null },
          after: { deletedAt: null },
        },
        tx,
      )
    })

    outcome = { ok: t('media.ok_restored') }
  } catch (error) {
    if (isRedirectError(error)) throw error
    outcome = { err: errorMessage(error) }
  }

  redirect(withOutcome(returnTo(form), outcome))
}

/**
 * Clear the placeholder credit on a row whose artwork has been replaced.
 *
 * Not merely cosmetic: the credit is what tells an operator — and this
 * codebase — which imagery is still generated stand-in art rather than
 * licensed photography.
 */
export async function clearPlaceholderCredit(id: string, form: FormData): Promise<void> {
  const session = await requireCapability('media.upload')
  const { t } = await getAdminI18n()
  let outcome: Outcome

  try {
    const credit = freq(form, 'credit', t('media.credit'))

    await db.transaction(async (tx) => {
      const [before] = await tx.select().from(media).where(eq(media.id, id)).limit(1)
      if (!before) throw new Error(t('media.err_gone'))
      if (!isPlaceholder(before.credit)) {
        throw new Error(t('media.err_not_placeholder'))
      }

      await tx.update(media).set({ credit }).where(eq(media.id, id))

      await writeAudit(
        {
          actor: session,
          action: 'media.credit',
          entityType: 'media',
          entityId: id,
          before: { credit: before.credit },
          after: { credit },
        },
        tx,
      )
    })

    outcome = { ok: t('media.ok_credit') }
  } catch (error) {
    if (isRedirectError(error)) throw error
    outcome = { err: errorMessage(error) }
  }

  redirect(withOutcome(returnTo(form), outcome))
}

/**
 * Where to land after a mutation.
 *
 * The grid is paged and filtered, so returning to a bare `/media` would throw
 * away the operator's place in a 52-row list every time they saved an alt
 * text. The value comes from a hidden input the page renders, and it is
 * rebuilt from parts rather than trusted: a `returnTo` that could carry an
 * arbitrary string straight into `redirect()` is an open redirect.
 */
function returnTo(form: FormData): string {
  const query = form.get('returnQuery')
  if (typeof query !== 'string' || query === '') return LIST

  const params = new URLSearchParams()
  for (const [key, value] of new URLSearchParams(query)) {
    if (key === 'ok' || key === 'err') continue
    if (!/^[a-zA-Z]+$/.test(key)) continue
    params.set(key, value.slice(0, 200))
  }

  const text = params.toString()
  return text === '' ? LIST : `${LIST}?${text}`
}
